#!/bin/sh
# Regenerates docs/database/schema.sql from the running Postgres container (after the services applied their migrations).
#   CONTAINER=aicos-postgres ./scripts/dump-schema.sh
set -eu
root="$(cd "$(dirname "$0")/.." && pwd)"
container="${CONTAINER:-aicos-postgres}"
user="${POSTGRES_USER:-aicos_admin}"
prefix="${POSTGRES_DB:-aicos}"
{
  echo "-- AICOS database DDL, generated by 'pg_dump --schema-only' from a PostgreSQL 16 instance whose schemas were built by the EF Core migrations of every service."
  echo "-- Regenerate with scripts/dump-schema.sh. One logical database per service (${prefix}_<service>), each with one schema of the same name;"
  echo "-- roles, databases and schemas are created by infra/postgres/init/01-schemas-and-roles.sh."
  for svc in identity menu table_reservation ordering payment kitchen workforce reporting customer; do
    echo
    echo "-- ============================================================ database ${prefix}_${svc}"
    docker exec "$container" pg_dump -U "$user" -d "${prefix}_${svc}" --schema-only --no-owner --no-privileges -n "$svc"
  done
} > "$root/docs/database/schema.sql"
echo "Wrote docs/database/schema.sql"
