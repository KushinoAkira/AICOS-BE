#!/bin/sh
# Regenerates docs/database/schema.sql from the running Postgres container (after the services applied their migrations).
#   CONTAINER=aicos-postgres ./scripts/dump-schema.sh
set -eu
root="$(cd "$(dirname "$0")/.." && pwd)"
container="${CONTAINER:-aicos-postgres}"
user="${POSTGRES_USER:-aicos_admin}"
db="${POSTGRES_DB:-aicos}"
{
  echo "-- AICOS database DDL, generated by 'pg_dump --schema-only' from a PostgreSQL 16 instance whose schema was built by the EF Core migrations of every service."
  echo "-- Regenerate with scripts/dump-schema.sh. One schema per service; roles and schemas are created by infra/postgres/init/01-schemas-and-roles.sh."
  echo
  docker exec "$container" pg_dump -U "$user" -d "$db" --schema-only --no-owner --no-privileges \
    -n identity -n menu -n table_reservation -n ordering -n payment -n kitchen -n workforce -n reporting -n customer
} > "$root/docs/database/schema.sql"
echo "Wrote docs/database/schema.sql"
